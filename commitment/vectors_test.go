var (
	goldenOnce  sync.Once
	goldenRoots [][32]byte
)

// goldenRoot returns the golden [RFC 6962] §2.1 root for a tree of n leaves.
func goldenRoot(t *testing.T, n int) [32]byte {
	t.Helper()
	goldenOnce.Do(func() {
		for _, line := range strings.Fields(goldenRootsHex) {
			b, err := hex.DecodeString(line)
			if err != nil {
				t.Fatalf("decode golden root %q: got error %v, want nil", line, err)
			}
			if len(b) != 32 {
				t.Fatalf("decode golden root %q: got %d bytes, want 32", line, len(b))
			}
			var h [32]byte
			copy(h[:], b)
			goldenRoots = append(goldenRoots, h)
		}
	})
	if n < 1 || n > len(goldenRoots) {
		t.Fatalf("goldenRoot(%d): got %d golden roots, want index in 1..%d", n, len(goldenRoots), len(goldenRoots))
	}
	return goldenRoots[n-1]
}

// TestVectors_RootMatrix builds a commitment for every size n in 1..1027 and
// asserts c.Root equals both an independent merkle.New computation over the
// sorted leaf digests and the golden cross-implementation root.
// Vector: [RFC 6962] §2.1 — Vector: [FIPS 180-4]
func TestVectors_RootMatrix(t *testing.T) {
	t.Parallel()

	for n := 1; n <= 1027; n++ {
		t.Run(fmt.Sprintf("n%d", n), func(t *testing.T) {
			t.Parallel()
			c := mustBuild(t, vectorObjects(n))
			if c.Size != n {
				t.Errorf("Size for n=%d: got %d, want %d", n, c.Size, n)
			}
			tree, err := merkle.New(sortedVectorLeaves(n))
			if err != nil {
				t.Fatalf("merkle.New for n=%d: got error %v, want nil", n, err)
			}
			if subtle.ConstantTimeCompare(c.Root[:], tree.Root()) != 1 {
				t.Errorf("Root for n=%d: got %x, want independent merkle.New root %x", n, c.Root, tree.Root())
			}
			want := goldenRoot(t, n)
			if subtle.ConstantTimeCompare(c.Root[:], want[:]) != 1 {
				t.Errorf("Root for n=%d: got %x, want golden [RFC 6962] §2.1 root %x", n, c.Root, want)
			}
		})
	}
}

// TestVectors_InclusionAllIndices proves InclusionProof + VerifyInclusion
// succeed for every leaf index of every tested size: all of 1..64 plus the
// power-of-two boundaries and their neighbors up to 1027.
func TestVectors_InclusionAllIndices(t *testing.T) {
	t.Parallel()

	sizes := make([]int, 0, 64+12)
	for n := 1; n <= 64; n++ {
		sizes = append(sizes, n)
	}
	sizes = append(sizes, 127, 128, 129, 255, 256, 257, 511, 512, 513, 1023, 1024, 1025, 1027)

	for _, n := range sizes {
		t.Run(fmt.Sprintf("n%d", n), func(t *testing.T) {
			t.Parallel()
			objects := vectorObjects(n)
			c := mustBuild(t, objects)
			byLeaf := make(map[[32]byte]TrustObject, n)
			for _, o := range objects {
				h, err := o.LeafHash()
				if err != nil {
					t.Fatalf("LeafHash for n=%d: got error %v, want nil", n, err)
				}
				byLeaf[h] = o
			}
			for i := 0; i < n; i++ {
				obj, ok := byLeaf[c.LeafHashes[i]]
				if !ok {
					t.Fatalf("no object for committed leaf %d of %d", i, n)
				}
				p, err := InclusionProof(c, obj)
				if err != nil {
					t.Fatalf("InclusionProof(leaf %d of %d): got error %v, want nil", i, n, err)
				}
				if p.Index != i {
					t.Errorf("Index for leaf %d of %d: got %d, want %d", i, n, p.Index, i)
				}
				if p.TreeSize != n {
					t.Errorf("TreeSize for leaf %d of %d: got %d, want %d", i, n, p.TreeSize, n)
				}
				if err := VerifyInclusion(c.Root, p, obj); err != nil {
					t.Errorf("VerifyInclusion(leaf %d of %d): got error %v, want nil", i, n, err)
				}
			}
		})
	}
}

// TestVectors_RFC6962Golden verifies the d0..d{9} leaf sets against the
// golden roots through the testObject adapter: each object's LeafHash is
// SHA-256("d{i}"), Build sorts and commits them, and the resulting root
// must equal the independently transcribed [RFC 6962] §2.1 MTH root.
// Vector: [RFC 6962] §2.1 — Vector: [FIPS 180-4]
func TestVectors_RFC6962Golden(t *testing.T) {
	t.Parallel()

	for n := 1; n <= 10; n++ {
		t.Run(fmt.Sprintf("d0_to_d%d", n-1), func(t *testing.T) {
			t.Parallel()
			objects := vectorObjects(n)
			c := mustBuild(t, objects)
			want := goldenRoot(t, n)
			if subtle.ConstantTimeCompare(c.Root[:], want[:]) != 1 {
				t.Fatalf("Root for leaf set d0..d%d: got %x, want golden root %x", n-1, c.Root, want)
			}
			// Every leaf of the vector set must prove inclusion against the
			// golden root — the proof is checked against the published-value
			// root, not c.Root, so the check covers construction too.
			for _, obj := range objects {
				p, err := InclusionProof(c, obj)
				if err != nil {
					t.Fatalf("InclusionProof for n=%d: got error %v, want nil", n, err)
				}
				if err := VerifyInclusion(want, p, obj); err != nil {
					t.Errorf("VerifyInclusion against golden root for n=%d: got error %v, want nil", n, err)
				}
			}
		})
	}
}
