// testObject is a TrustObject whose leaf is the deterministic [FIPS 180-4]
// SHA-256 digest of the [RFC 6962] vector leaf name "d{seed}", so tests can
// build fixed leaf sets without constructing real trust objects.
type testObject struct{ seed int }

// LeafHash returns vectorLeaf(o.seed).
func (o testObject) LeafHash() ([32]byte, error) { return vectorLeaf(o.seed), nil }

// vectorLeaf returns SHA-256("d{seed}") — a deterministic 32-byte leaf digest.
// Vector: [FIPS 180-4] SHA-256 over the RFC 6962 §2.1 leaf names d0, d1, ...
func vectorLeaf(seed int) [32]byte {
	return sha256.Sum256([]byte(fmt.Sprintf("d%d", seed)))
}

// vectorObjects returns n TrustObjects seeded 0..n-1.
func vectorObjects(n int) []TrustObject {
	objs := make([]TrustObject, n)
	for i := range objs {
		objs[i] = testObject{seed: i}
	}
	return objs
}

// sortedVectorLeaves returns the leaf digests for seeds 0..n-1 in ascending
// bytewise order — the exact leaf order Build commits to merkle.New.
func sortedVectorLeaves(n int) [][]byte {
	leaves := make([][32]byte, n)
	for i := range leaves {
		leaves[i] = vectorLeaf(i)
	}
	sort.Slice(leaves, func(i, j int) bool {
		return bytes.Compare(leaves[i][:], leaves[j][:]) < 0
	})
	out := make([][]byte, n)
	for i := range leaves {
		out[i] = leaves[i][:]
	}
	return out
}

